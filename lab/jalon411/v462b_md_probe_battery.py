def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def strip_c_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    return src


def extract_struct(text, tag="GSP_WPR2_READ_STATE"):
    i = text.rfind("typedef struct", 0, text.find("} " + tag + ";"))
    j = text.find("} " + tag + ";")
    assert i >= 0 and j > i, "the struct text not found"
    return text[i:j + len("} " + tag + ";") + 1]


def extract_codes(text, prefix="GSP_WPR2_READ_(?:V|C)_"):
    return sorted(re.findall(rf"#define ({prefix}\w+)\s+(\d+)", text))


