def fixture_fields(**over):
    """The stub-scale green GspFwWprMeta field dict (the v462a
    fixture law, rescaled: the structural relations IDENTICAL)."""
    f = {
        "magic": v462a.META_MAGIC, "revision": v462a.META_REVISION,
        "gspFwRsvdStart": 0x1F0000, "nonWprHeapOffset": 0x1F0000,
        "nonWprHeapSize": 0x10000,
        "gspFwWprStart": F_WS, "gspFwHeapOffset": F_HOFF,
        "gspFwHeapSize": F_HSZ, "gspFwOffset": F_FWOFF,
        "bootBinOffset": F_BOOTBIN, "frtsOffset": F_FRTSOFF,
        "frtsSize": F_FRTSZ, "gspFwWprEnd": F_WE,
        "fbSize": F_FB, "bootCount": 1,
        "gspFwHeapFreeListWprOffset": 0x1000,
        "verified": v462a.META_VERIFIED,
    }
    f.update(over)
    return f


def fixture_plan(f, s4_regions=None):
    """The windows from the fixture fields (the v462a math itself)."""
    wins = v462a.compute_windows(f, s4_regions=s4_regions)
    return wins


def build_fixture_plans():
    """The THREE variants (the v461b cross-instrument law — the
    battery tests v462a's OWN emission):
      plan_a  the single ABS survivor (the green fixture)
      plan_b  the GATED NULL plan (no windows)
      plan_c  the 2-window plan (the ABS + the S4 region — sel=2
              exercises the per-window describe->map->copy chain)
    """
    f_a = fixture_fields()
    wins_a = fixture_plan(f_a)
    assert (len(wins_a["survivors"]) == 1 and
            wins_a["survivors"][0]["win_class"] == v462a.WIN_ABS), \
        "the fixture-a model drift — refusing"

    wins_b = {"survivors": []}

    f_c = fixture_fields()
    s4 = [{"slot": 3, "id8": 0, "name": "HEAP2", "pa": 0x180000,
           "size": 0x20000, "kind_raw": 1, "loc_raw": 2,
           "state": "VALID"}]
    wins_c = fixture_plan(f_c, s4_regions=s4)
    assert len(wins_c["survivors"]) == 2, "the fixture-c model drift"

    return (list(wins_a["survivors"]),
            list(wins_b["survivors"]),
            list(wins_c["survivors"]))


