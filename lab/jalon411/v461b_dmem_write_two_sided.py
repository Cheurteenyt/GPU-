def g4_layout():
    rm_s = extract_struct(strip_c_comments(RM_C.read_text()))
    pt = PATCHER.read_text()
    i0 = pt.find("#define GSP_DMEM_WRITE_V_OFF")
    i1 = pt.find("} GSP_DMEM_WRITE_STATE;")
    block = pt[i0:i1 + len("} GSP_DMEM_WRITE_STATE;") + 1]
    nv_s = extract_struct(block)
    out_rm, err = struct_probe_outputs(rm_s, "rm")
    if out_rm is None:
        check("G4 the rm struct compiles", False, err)
        return
    out_nv, err = struct_probe_outputs(nv_s, "nv")
    if out_nv is None:
        check("G4 the nv struct compiles", False, err)
        return
    check("G4 the layout mirrors byte-for-byte", out_rm == out_nv)


