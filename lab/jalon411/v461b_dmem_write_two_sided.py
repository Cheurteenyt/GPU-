def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def strip_c_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    return src


def extract_struct(text, tag="GSP_DMEM_WRITE_STATE"):
    i = text.rfind("typedef struct", 0, text.find("} " + tag + ";"))
    j = text.find("} " + tag + ";")
    assert i >= 0 and j > i, "the struct text not found"
    return text[i:j + len("} " + tag + ";") + 1]


def extract_codes(text):
    return sorted(re.findall(r"#define (GSP_DMEM_WRITE_V_\w+)\s+(\d+)",
                             text))


