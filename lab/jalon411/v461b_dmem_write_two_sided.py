def g5_patcher_dry_run():
    with tempfile.TemporaryDirectory() as td:
        tdp = Path(td)
        nv = tdp / "nv.c"
        nv.write_text(FIXTURE_NV)
        env = dict(**__import__("os").environ,
                   NV_C_461_PATH=str(nv))
        r = run([sys.executable, str(PATCHER)], env=env)
        if not check("G5 the patcher runs", r.returncode == 0,
                     r.stderr[:200]):
            return
        s = nv.read_text()
        check("G5 the marker present", "DmemWriteMarker" in s)
        anchor = "static int __init nvidia_init_module(void)"
        check("G5 the init anchor stays unique", s.count(anchor) == 1)
        check("G5 the arm after nv_memdbg_init",
              s.index("nv_memdbg_init();") <
              s.index("dmem_write_armed"))
        decl_pos = s.find("} GSP_DMEM_WRITE_STATE;")
        worker_pos = s.find("static void gsp_dmem_write_worker"
                            "(struct work_struct *w)\n{")
        init_pos = s.index(anchor)
        check("G5 the worker BODY found (not the forward decl)",
              worker_pos > 0)
        check("G5 the worker body AFTER its declarations",
              0 < decl_pos < worker_pos < init_pos)
        check("G5 the names table before the worker body",
              s.find("gsp_dmem_write_verdict_names_nv") < worker_pos)
