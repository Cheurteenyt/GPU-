SURF_ID = 3            # the statemonitor in the fixture plan
SURF_SIZE = 1 << 18


def build_fixture_plans():
    import random
    rng = random.Random(0x4611)
    OB = 0x20000
    buf = bytearray(rng.randbytes(SURF_SIZE))
    for k in range(v461a.N_GROUPS):
        v = v461a.SHAPE_250 if k != 2 else v461a.SHAPE_240
        off = OB + v461a.BASE_OFF + k * v461a.GROUP_STRIDE
        buf[off:off + 4] = struct.pack("<I", v)
        buf[off + 4:off + 8] = b"\x00" * 4
        ro = OB + v461a.REC_STRIDE * k + v461a.F18_OFF
        buf[ro:ro + 4] = struct.pack("<I", v461a.F18_STOCK)
    sc = v461a.scan_surface("fixture-full", bytes(buf))
    assert sc["object"]["verdict"] == "OBJECT-FOUND"
    plan_a = v461a.build_plan({"fixture-full": sc}, {"fixture-full": SURF_ID})
    plan_b = v461a.build_plan({}, {})           # the GATED NULL
    plan_c = v461a.build_plan({"fixture-full": sc}, {"fixture-full": 5})
    return plan_a, plan_b, plan_c


