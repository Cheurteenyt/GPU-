def struct_probe_outputs(struct_text, tag):
    prints = "\n".join(
        f'  printf("off {m} %zu\\n", offsetof(GSP_DMEM_WRITE_STATE, {m}));'
        for m in OFFSETS)
    with tempfile.TemporaryDirectory() as td:
        p = Path(td) / "probe.c"
        p.write_text(PROBE_TMPL.format(struct_text=struct_text,
                                       prints=prints))
        r = run(["gcc", "-o", str(Path(td) / "probe"), str(p)])
        if r.returncode != 0:
            return None, f"gcc FAIL: {r.stderr[:200]}"
        r = run([str(Path(td) / "probe")])
        if r.returncode != 0:
            return None, f"run FAIL: {r.stderr[:200]}"
