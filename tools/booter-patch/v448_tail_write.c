    p[0x59c + 0] = 0x7e; p[0x59c + 1] = 0xca; p[0x59c + 2] = 0xde; p[0x59c + 3] = 0xc0; // canari
    p[0x5a0 + 0] = 0x00; p[0x5a0 + 1] = 0x00; p[0x5a0 + 2] = 0x00; p[0x5a0 + 3] = 0x00; // pad
    p[0x5a4 + 0] = 0x00; p[0x5a4 + 1] = 0x00; p[0x5a4 + 2] = 0x00; p[0x5a4 + 3] = 0x00;
